    // "rabbit" and "minecraft:rabbit" are the same mob, like everywhere else an id is typed.
    private static String normalizeEntityId(String raw) {
        if (raw == null) {
            return null;
        }
        String id = raw.trim().toLowerCase(Locale.ROOT);
        if (id.isEmpty()) {
            return null;
        }
        return id.indexOf(':') < 0 ? "minecraft:" + id : id;
    }

    private static String formatSpawnGroupEntry(String id, int[] size) {
        return size[0] == size[1] ? id + "|" + size[0] : id + "|" + size[0] + "|" + size[1];
    }

    // The id half of parseSpawnGroupSizes' rules, shared so a menu edit and a hand-written line
    // agree on what counts as the same mob: lower case, and this mod's namespace when none is given.
    private static String normalizeSpawnGroupId(String raw) {
        if (raw == null) {
            return null;
        }
        String id = raw.trim().toLowerCase(Locale.ROOT);
        if (id.isEmpty()) {
            return null;
        }
        return id.indexOf(':') < 0 ? "alexsmobs:" + id : id;
    }

    // "<entity id>|<min>|<max>", or "<entity id>|<count>" for a fixed size. The namespace may be
    // left off, in which case this mod's own is assumed. A malformed entry is warned about and
    // skipped rather than throwing: bake() runs inside one try, so one bad line must not cost the
    // rest of the config.
    private static void parseSpawnGroupSizes() {
        SPAWN_GROUP_SIZES.clear();
        for (String entry : spawnGroupSizes) {
            if (entry == null || entry.trim().isEmpty()) {
                continue;
            }
            String[] parts = entry.split("\\|");
            if (parts.length < 2 || parts.length > 3) {
                warnSpawnGroupSize(entry, "expected \"<entity id>|<min>|<max>\" or \"<entity id>|<count>\"");
                continue;
            }
            String id = normalizeSpawnGroupId(parts[0]);
            if (id == null) {
                warnSpawnGroupSize(entry, "no entity id");
                continue;
            }
            int min;
            int max;
            try {
                min = Integer.parseInt(parts[1].trim());
                max = parts.length == 3 ? Integer.parseInt(parts[2].trim()) : min;
            } catch (NumberFormatException e) {
                warnSpawnGroupSize(entry, "the group size must be a whole number");
                continue;
            }
            if (min < 1 || max < min) {
                warnSpawnGroupSize(entry, "needs 1 <= min <= max; set the mob's spawn weight to 0 to stop it spawning");
                continue;
            }
            SPAWN_GROUP_SIZES.put(id, new int[]{min, max});
        }
    }

    private static void warnSpawnGroupSize(String entry, String why) {
        AlexsMobs.LOGGER.warn("Ignoring spawnGroupSizes entry \"" + entry + "\": " + why + ".");
    }

