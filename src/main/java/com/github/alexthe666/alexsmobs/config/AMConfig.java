    /**
     * How many of one mob a single natural-spawn attempt should place, given the pack size this mod
     * would otherwise have used. Returns {@code min}/{@code max} unchanged unless spawnGroupSizes
     * names this entity, so an untouched config reproduces the old numbers exactly.
     *
     * @param entityId full registry id, e.g. {@code "alexsmobs:orca"}; null is tolerated
     */
    public static int[] spawnGroupSize(String entityId, int min, int max) {
        if (entityId != null) {
            SPAWN_GROUP_DEFAULTS.putIfAbsent(entityId, new int[]{min, max});
            if (!SPAWN_GROUP_SIZES.isEmpty()) {
                int[] override = SPAWN_GROUP_SIZES.get(entityId);
                if (override != null) {
                    return new int[]{override[0], override[1]};
                }
            }
        }
        return new int[]{min, max};
    }

    /**
     * Every mob this mod spawns naturally, in id order, against the pack size it uses when nothing
     * overrides it. Populated as a world's registries are built, so it is empty until then.
     *
     * @return an unmodifiable view; the {@code int[]} values are the live arrays, don't write to them
     */
    public static Map<String, int[]> spawnGroupDefaults() {
        return Collections.unmodifiableMap(SPAWN_GROUP_DEFAULTS);
    }

    /** The override in force for one mob, or null if it spawns at its default pack size. */
    public static int[] spawnGroupOverride(String entityId) {
        int[] override = entityId == null ? null : SPAWN_GROUP_SIZES.get(entityId);
        return override == null ? null : new int[]{override[0], override[1]};
    }

    /**
     * Adds, replaces or removes one mob's entry in {@code spawnGroupSizes} and saves the file.
     * Passing null for {@code size} removes it, which is how the menu drops an override that has
     * been dialled back to the mob's default.
     *
     * <p>Rewrites the list <b>entry by entry</b> rather than regenerating it from the parsed map, so
     * an entry naming another mod's mob, or one that failed to parse, survives an edit made here
     * untouched. Only the line for this mob is rewritten.
     */
    public static boolean setSpawnGroupOverride(String entityId, int[] size) {
        String id = normalizeSpawnGroupId(entityId);
        if (id == null) {
            return false;
        }
        List<String> out = new ArrayList<>();
        boolean replaced = false;
        for (String entry : ConfigHolder.COMMON.spawnGroupSizes.get()) {
            if (entry == null || entry.trim().isEmpty()) {
                continue;
            }
            if (!id.equals(normalizeSpawnGroupId(entry.split("\\|")[0]))) {
                out.add(entry);
                continue;
            }
            if (size != null && !replaced) {
                out.add(formatSpawnGroupEntry(id, size));
                replaced = true;
            }
        }
        if (size != null && !replaced) {
            out.add(formatSpawnGroupEntry(id, size));
        }
        ConfigHolder.COMMON.spawnGroupSizes.setFromString(String.join(",", out));
        return ConfigHolder.save();
    }

    /**
     * Puts every mob this mod spawns back on its stock pack size.
     *
     * <p>Keeps any line naming something that is <b>not</b> one of this mod's spawn entries, for the
     * same reason {@link #setSpawnGroupOverride} does: the button undoes edits made here, and a line
     * someone wrote by hand for another mod's mob is not one of them. Clearing the whole option is
     * still one {@code /amc config reset spawnGroupSizes} away.
     */
    public static boolean clearSpawnGroupOverrides() {
        List<String> out = new ArrayList<>();
        for (String entry : ConfigHolder.COMMON.spawnGroupSizes.get()) {
            if (entry == null || entry.trim().isEmpty()) {
                continue;
            }
            String id = normalizeSpawnGroupId(entry.split("\\|")[0]);
            if (id == null || !SPAWN_GROUP_DEFAULTS.containsKey(id)) {
                out.add(entry);
            }
        }
        ConfigHolder.COMMON.spawnGroupSizes.setFromString(String.join(",", out));
        return ConfigHolder.save();
    }

