    /**
     * Turns one mob on or off in {@code roadrunnerTargets} and saves the file. Other lines are kept
     * as they were written, so a hand-typed id the menu has never heard of survives the edit.
     */
    public static boolean setRoadrunnerTarget(String entityId, boolean hunt) {
        String id = normalizeEntityId(entityId);
        if (id == null) {
            return false;
        }
        List<String> out = new ArrayList<>();
        for (String entry : ConfigHolder.COMMON.roadrunnerTargets.get()) {
            if (entry != null && !entry.trim().isEmpty() && !id.equals(normalizeEntityId(entry))) {
                out.add(entry);
            }
        }
        if (hunt) {
            out.add(id);
        }
        ConfigHolder.COMMON.roadrunnerTargets.setFromString(String.join(",", out));
        return ConfigHolder.save();
    }

